# Band-limited saw: naive saw with the jump replaced by a smooth half-sine step
# that lasts N samples-worth of phase (N = sr / (2.5 * freq), sent in as a signal).
bs = Canvas(w=700, h=600)
bs.comment("Band-limited saw. Left: frequency (signal). Right: N = sr / (2.5 * freq).", 20, 5)
b_f = bs.obj("inlet~", 20, 30)
b_n = bs.obj("inlet~", 300, 30)
ph = bs.obj("phasor~", 20, 60)
bs.c(b_f, 0, ph, 0)
naive = bs.obj("-~ 0.5", 20, 90)
bs.c(ph, 0, naive, 0)
u1 = bs.obj("+~ 0.5", 150, 90)
bs.c(ph, 0, u1, 0)
u2 = bs.obj("wrap~", 150, 115)
u3 = bs.obj("-~ 0.5", 150, 140)
bs.chain(u1, u2, u3)
st1 = bs.obj("*~ 1e+06", 150, 170)
st2 = bs.obj("clip~ -0.5 0.5", 150, 195)
bs.chain(u3, st1, st2)
w1 = bs.obj("*~", 300, 170)
bs.c(u3, 0, w1, 0)
bs.c(b_n, 0, w1, 1)
w2 = bs.obj("clip~ -0.5 0.5", 300, 195)
w3 = bs.obj("*~ 0.5", 300, 220)
w4 = bs.obj("-~ 0.25", 300, 245)
w5 = bs.obj("cos~", 300, 270)
w6 = bs.obj("*~ 0.5", 300, 295)
bs.chain(w1, w2, w3, w4, w5, w6)
a1 = bs.obj("+~", 20, 330)
bs.c(naive, 0, a1, 0)
bs.c(st2, 0, a1, 1)
a2 = bs.obj("-~", 20, 360)
bs.c(a1, 0, a2, 0)
bs.c(w6, 0, a2, 1)
bs.c(a2, 0, bs.obj("outlet~", 20, 400), 0)
bs.save(os.path.join(OUT, "bsaw.pd"))

# --- DSP subpatch, switched off while the voice is silent
d = Canvas("dsp", w=1100, h=800)
d_ip = d.obj("inlet", 20, 20)
d_ia = d.obj("inlet", 400, 20)
d_it = d.obj("inlet", 650, 20)
d_is = d.obj("inlet", 900, 20)
sw = d.obj("switch~", 900, 60)
d.c(d_is, 0, sw, 0)

pl = d.obj("line~", 20, 60)
d.c(d_ip, 0, pl, 0)
vib = d.obj("r~ mpe-vib", 110, 60)
padd = d.obj("+~", 20, 90)
d.c(pl, 0, padd, 0)
d.c(vib, 0, padd, 1)
mt = d.obj("mtof~", 20, 115)
d.c(padd, 0, mt, 0)
f = d.obj("clip~ 1 20000", 20, 140)
d.c(mt, 0, f, 0)
# N = (sr/2.5) / f
rk = d.obj("r~ mpe-sawk", 120, 165)
nn = d.obj("/~", 120, 190)
d.c(rk, 0, nn, 0)
d.c(f, 0, nn, 1)
# detune: f*(1-d), f*(1+d)
rdt = d.obj("r~ mpe-detune", 260, 140)
dm = d.obj("*~", 260, 165)
d.c(f, 0, dm, 0)
d.c(rdt, 0, dm, 1)
flo = d.obj("-~", 200, 220)
d.c(f, 0, flo, 0)
d.c(dm, 0, flo, 1)
fhi = d.obj("+~", 300, 220)
d.c(f, 0, fhi, 0)
d.c(dm, 0, fhi, 1)
saws = []
for i, src in enumerate((f, flo, fhi)):
    s = d.obj("bsaw", 20 + i * 140, 260)
    d.c(src, 0, s, 0)
    d.c(nn, 0, s, 1)
    saws.append(s)
side = d.obj("+~", 160, 290)
d.c(saws[1], 0, side, 0)
d.c(saws[2], 0, side, 1)
sideg = d.obj("*~ 0.8", 160, 315)
d.c(side, 0, sideg, 0)
mix1 = d.obj("+~", 20, 340)
d.c(saws[0], 0, mix1, 0)
d.c(sideg, 0, mix1, 1)
# sub oscillator (sine, one octave down)
fsub = d.obj("*~ 0.5", 460, 260)
d.c(f, 0, fsub, 0)
osub = d.obj("osc~", 460, 285)
d.c(fsub, 0, osub, 0)
rsub = d.obj("r~ mpe-sub", 540, 285)
gsub = d.obj("*~", 460, 310)
d.c(osub, 0, gsub, 0)
d.c(rsub, 0, gsub, 1)
mix2 = d.obj("+~", 20, 370)
d.c(mix1, 0, mix2, 0)
d.c(gsub, 0, mix2, 1)
mixg = d.obj("*~ 0.45", 20, 395)
d.c(mix2, 0, mixg, 0)

env = d.obj("line~", 400, 60)
d.c(d_ia, 0, env, 0)
tbl = d.obj("line~", 650, 60)
d.c(d_it, 0, tbl, 0)

# cutoff (MIDI units) = cut + env*breathamt + (timbre-0.5)*24 + (pitch-60)*0.5
rcut = d.obj("r~ mpe-cut", 650, 120)
rbam = d.obj("r~ mpe-bamt", 500, 90)
eb = d.obj("*~", 400, 120)
d.c(env, 0, eb, 0)
d.c(rbam, 0, eb, 1)
c1 = d.obj("+~", 400, 150)
d.c(eb, 0, c1, 0)
d.c(rcut, 0, c1, 1)
tb1 = d.obj("-~ 0.5", 760, 90)
d.c(tbl, 0, tb1, 0)
tb2 = d.obj("*~ 24", 760, 115)
d.c(tb1, 0, tb2, 0)
c2 = d.obj("+~", 400, 180)
d.c(c1, 0, c2, 0)
d.c(tb2, 0, c2, 1)
kt1 = d.obj("-~ 60", 560, 180)
d.c(pl, 0, kt1, 0)
kt2 = d.obj("*~ 0.5", 560, 205)
d.c(kt1, 0, kt2, 0)
c3 = d.obj("+~", 400, 230)
d.c(c2, 0, c3, 0)
d.c(kt2, 0, c3, 1)
cc = d.obj("clip~ 0 135", 400, 255)
cm = d.obj("mtof~", 400, 280)
ch = d.obj("clip~ 20 16000", 400, 305)
d.chain(c3, cc, cm, ch)

# two resonant lowpass stages (only the first one resonates)
rres = d.obj("r mpe-res", 560, 400)
vcf1 = d.obj("vcf~ 1", 20, 440)
d.c(mixg, 0, vcf1, 0)
d.c(ch, 0, vcf1, 1)
d.c(rres, 0, vcf1, 2)
vcf2 = d.obj("vcf~ 0.7", 20, 480)
d.c(vcf1, 1, vcf2, 0)
d.c(ch, 0, vcf2, 1)

# gentle saturation: y = clip(x*1.3), out = y - 0.148*y^3
drv = d.obj("*~ 1.3", 20, 520)
d.c(vcf2, 1, drv, 0)
yc = d.obj("clip~ -1.5 1.5", 20, 545)
d.c(drv, 0, yc, 0)
y2 = d.obj("*~", 120, 570)
d.c(yc, 0, y2, 0)
d.c(yc, 0, y2, 1)
y3 = d.obj("*~", 120, 595)
d.c(y2, 0, y3, 0)
d.c(yc, 0, y3, 1)
y3s = d.obj("*~ -0.148148", 120, 620)
d.c(y3, 0, y3s, 0)
ysum = d.obj("+~", 20, 650)
d.c(yc, 0, ysum, 0)
d.c(y3s, 0, ysum, 1)
vca = d.obj("*~", 20, 690)
d.c(ysum, 0, vca, 0)
d.c(env, 0, vca, 1)
d.c(vca, 0, d.obj("outlet~", 20, 730), 0)

