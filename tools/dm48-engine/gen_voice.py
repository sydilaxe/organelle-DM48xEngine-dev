"""voice.pd: one host voice. Note allocation data in, engine loaded dynamically into [pd $0-slot]."""
import os
from pdgen import Canvas

BEND = "engbend"   # semitones per internal channel (no hyphens: used in [expr])
JUST = "engjust"   # just-intonation offsets per pitch class


def build(out_dir):
    v = Canvas(w=1200, h=900)
    v.comment("Host voice. Input from [poly]: 'key vel', key = channel * 128 + note.", 20, 5)
    v.comment("Internal channels: 17 * loop layer + MIDI channel (0 = Organelle keys). Master = 17 * layer + 1.", 20, 22)
    i_in = v.obj("inlet", 20, 50)
    unp = v.obj("unpack 0 0", 20, 75)
    v.c(i_in, 0, unp, 0)
    velf = v.obj("f", 20, 125)
    keyt = v.obj("t b f", 110, 100)
    v.c(unp, 1, velf, 1)
    v.c(unp, 0, keyt, 0)
    split = v.obj("expr int($f1 / 128); $f1 % 128", 160, 125)
    v.c(keyt, 1, split, 0)
    v.c(keyt, 0, velf, 0)
    sel0 = v.obj("sel 0", 20, 150)
    v.c(velf, 0, sel0, 0)

    # outputs to the engine (via sends that the dynamic slot listens to)
    s_pitch = v.obj("s $0-pitch", 20, 840)
    s_level = v.obj("s $0-level", 150, 840)
    s_timb = v.obj("s $0-timbre", 280, 840)

    # --- note on
    on_t = v.obj("t b f b", 80, 180)
    v.c(sel0, 1, on_t, 0)
    act1 = v.msg("1", 160, 210)
    v.c(on_t, 2, act1, 0)
    stopm = v.msg("stop", 200, 210)
    v.c(on_t, 2, stopm, 0)
    tbr = v.msg("0.5 0", 250, 210)
    v.c(on_t, 2, tbr, 0)
    v.c(tbr, 0, s_timb, 0)
    velc = v.obj("expr pow($f1 / 127, $f2)", 80, 240)
    v.c(on_t, 1, velc, 0)
    v.c(v.obj("r eng-curve", 220, 240), 0, velc, 1)
    lvon = v.msg("$1 4", 80, 270)
    v.c(velc, 0, lvon, 0)
    v.c(lvon, 0, s_level, 0)
    PITCH = (f"expr $f2 + $f3 + {BEND}[$f1] + ($f1 != 17 * int($f1 / 17) + 1) * {BEND}[17 * int($f1 / 17) + 1]"
             f" + {JUST}[($f2 - $f4 + 120) % 12]")
    chA = v.obj("f", 20, 270)
    v.c(on_t, 0, chA, 0)
    pA = v.obj(PITCH, 20, 300)
    v.c(chA, 0, pA, 0)
    pjump = v.msg("$1 0", 20, 330)
    v.c(pA, 0, pjump, 0)
    v.c(pjump, 0, s_pitch, 0)

    # --- note off
    off_t = v.obj("t b b", 20, 380)
    v.c(sel0, 0, off_t, 0)
    act0 = v.msg("0", 120, 410)
    v.c(off_t, 1, act0, 0)
    relf = v.obj("f 200", 20, 410)
    v.c(v.obj("r eng-release", 20, 355), 0, relf, 1)
    v.c(off_t, 0, relf, 0)
    relt = v.obj("t f f", 20, 440)
    v.c(relf, 0, relt, 0)
    lvoff = v.msg("0 $1", 20, 470)
    v.c(relt, 0, lvoff, 0)
    v.c(lvoff, 0, s_level, 0)
    pad = v.obj("+ 50", 110, 470)
    v.c(relt, 1, pad, 0)
    dly = v.obj("delay 200", 110, 500)
    v.c(pad, 0, dly, 0)
    v.c(stopm, 0, dly, 0)
    swoff = v.msg("0", 110, 530)
    v.c(dly, 0, swoff, 0)

    # active flag -> the engines in this voice ([r $0-act]: 1 while the note sounds or releases)
    actf = v.obj("f 0", 410, 780)
    v.c(act1, 0, actf, 0)
    v.c(swoff, 0, actf, 0)
    v.c(actf, 0, v.obj("s $0-act", 410, 805), 0)
    # --- bend updates
    rb = v.obj("r eng-bend", 450, 50)
    bf = v.obj("expr ($f1 == $f2) || ($f1 == 17 * int($f2 / 17) + 1)", 450, 75)
    v.c(rb, 0, bf, 0)
    bs = v.obj("sel 1", 450, 100)
    v.c(bf, 0, bs, 0)
    chB = v.obj("f", 450, 125)
    v.c(bs, 0, chB, 0)
    pB = v.obj(PITCH, 450, 150)
    v.c(chB, 0, pB, 0)
    pgl = v.msg("$1 5", 450, 175)
    v.c(pB, 0, pgl, 0)
    v.c(pgl, 0, s_pitch, 0)
    for r, inl in (("r eng-octave", 2), ("r eng-key", 3)):
        o = v.obj(r, 800 + inl * 100, 125)
        v.c(o, 0, pA, inl)
        v.c(o, 0, pB, inl)

    # --- breath "ch note value" (note -1 = whole channel)
    rbr = v.obj("r eng-breath", 450, 230)
    brx = v.obj("expr if(($f1 == $f4) && (($f2 < 0) || ($f2 == $f5)) && $f6, $f3, -1)", 450, 255)
    v.c(rbr, 0, brx, 0)
    brm = v.obj("moses 0", 450, 280)
    v.c(brx, 0, brm, 0)
    brmsg = v.msg("$1 15", 510, 305)
    v.c(brm, 1, brmsg, 0)
    v.c(brmsg, 0, s_level, 0)
    # --- timbre "ch value"
    rtb = v.obj("r eng-timbre", 450, 350)
    tbx = v.obj("expr if(($f1 == $f3) && $f4, $f2, -1)", 450, 375)
    v.c(rtb, 0, tbx, 0)
    tbm = v.obj("moses 0", 450, 400)
    v.c(tbx, 0, tbm, 0)
    tbmsg = v.msg("$1 20", 510, 425)
    v.c(tbm, 1, tbmsg, 0)
    v.c(tbmsg, 0, s_timb, 0)

    for dst, inl in ((chA, 1), (chB, 1), (bf, 1), (brx, 3), (tbx, 2)):
        v.c(split, 0, dst, inl)
    for dst, inl in ((pA, 1), (pB, 1), (brx, 4)):
        v.c(split, 1, dst, inl)
    for g in (act1, act0):
        v.c(g, 0, brx, 5)
        v.c(g, 0, tbx, 3)

    # --- every engine is created once, at start-up, inside [pd $0-eng] (one [ehost] per engine).
    # Only the selected one runs (switch~); switching fades 15 ms out, then 15 ms in - nothing is created while
    # you play, so Pd never has to rebuild its DSP graph mid-performance.
    rc = v.obj("r eng-clear", 700, 450)
    idf = v.obj("f $0", 700, 475)
    v.c(rc, 0, idf, 0)
    v.c(idf, 0, v.msg("; pd-$1-eng clear", 700, 500), 0)
    ra = v.obj("r eng-add", 900, 450)                       # "index engines/NAME"
    at = v.obj("t a b", 900, 475)
    v.c(ra, 0, at, 0)
    idf2 = v.obj("f $0", 1000, 500)
    v.c(at, 1, idf2, 0)
    lp = v.obj("list prepend", 900, 525)
    v.c(idf2, 0, lp, 1)
    v.c(at, 0, lp, 0)
    v.c(lp, 0, v.msg("; pd-$1-eng obj 10 10 ehost $1 $3 $2", 900, 550), 0)
    v.sub(Canvas("$0-eng", w=500, h=300), 700, 600)
    v.c(v.obj("catch~ $0-out", 20, 870), 0, v.obj("outlet~", 20, 895), 0)
    v.save(os.path.join(out_dir, "voice.pd"))


def build_ehost(out_dir):
    """ehost.pd: one engine inside a voice.  Args: voice-id, engines/NAME, index."""
    h = Canvas(w=900, h=520)
    h.comment("One engine in one voice. Runs (switch~) only while it is the selected engine (eng-esel) and the voice "
              "sounds. Selected: waits 15 ms (the old engine fades out), then fades in over 15 ms.", 20, 5)
    p, l, t = h.obj("r $1-pitch", 20, 40), h.obj("r $1-level", 120, 40), h.obj("r $1-timbre", 220, 40)
    eng = h.obj("$2 eng", 20, 90)
    for i, src in enumerate((p, l, t)):
        h.c(src, 0, eng, i)
    g = h.obj("*~", 20, 140)
    h.c(eng, 0, g, 0)
    gl = h.obj("line~", 120, 115)
    h.c(gl, 0, g, 1)
    h.c(g, 0, h.obj("throw~ $1-out", 20, 170), 0)
    # stored state, read in order by the recompute below: act (voice sounds), sel, fading
    a2, s2, f2 = h.obj("f 0", 400, 340), h.obj("f 0", 450, 340), h.obj("f 0", 500, 340)
    rec = h.obj("t b b b", 400, 315)
    ex = h.obj("expr $f1 && ($f2 || $f3)", 400, 390)
    h.c(rec, 2, f2, 0)
    h.c(rec, 1, s2, 0)
    h.c(rec, 0, a2, 0)
    h.c(f2, 0, ex, 2)
    h.c(s2, 0, ex, 1)
    h.c(a2, 0, ex, 0)
    h.c(ex, 0, h.obj("switch~", 400, 415), 0)
    # voice on/off
    at = h.obj("t b f", 400, 65)
    h.c(h.obj("r $1-act", 400, 40), 0, at, 0)
    h.c(at, 1, a2, 1)
    h.c(at, 0, rec, 0)
    # selection
    sx = h.obj("== $3", 550, 40)
    h.c(h.obj("r eng-esel", 550, 15), 0, sx, 0)
    sc = h.obj("change -1", 550, 65)
    h.c(sx, 0, sc, 0)
    st = h.obj("t b f f", 550, 90)
    h.c(sc, 0, st, 0)
    h.c(st, 2, s2, 1)
    ss = h.obj("sel 1 0", 550, 115)
    h.c(st, 1, ss, 0)
    h.c(st, 0, rec, 0)
    # selected: no fading flag, fade in after 15 ms
    sel_t = h.obj("t b b b", 550, 140)
    h.c(ss, 0, sel_t, 0)
    dout = h.obj("delay 20", 750, 190)
    stp = h.msg("stop", 650, 165)
    h.c(sel_t, 2, stp, 0)
    h.c(stp, 0, dout, 0)
    z = h.msg("0", 600, 165)
    h.c(sel_t, 1, z, 0)
    h.c(z, 0, f2, 1)
    din = h.obj("delay 15", 550, 190)
    h.c(sel_t, 0, din, 0)
    fin = h.msg("1 15", 550, 215)
    h.c(din, 0, fin, 0)
    h.c(fin, 0, gl, 0)
    # deselected: fade out over 15 ms, keep running 20 ms (fading), then stop
    des_t = h.obj("t b b", 750, 140)
    h.c(ss, 1, des_t, 0)
    one = h.msg("1", 800, 165)
    h.c(des_t, 1, one, 0)
    h.c(one, 0, f2, 1)
    fout = h.msg("0 15", 850, 165)
    h.c(des_t, 0, fout, 0)
    h.c(fout, 0, gl, 0)
    h.c(des_t, 0, dout, 0)
    endf = h.obj("t b b", 750, 215)
    h.c(dout, 0, endf, 0)
    zz = h.msg("0", 800, 240)
    h.c(endf, 1, zz, 0)
    h.c(zz, 0, f2, 1)
    h.c(endf, 0, rec, 0)
    h.save(os.path.join(out_dir, "ehost.pd"))
