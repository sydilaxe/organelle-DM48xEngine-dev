"""voice.pd: one host voice. Note allocation data in, engine loaded dynamically into [pd $0-slot]."""
import os
from pdgen import Canvas

BEND = "engbend"   # semitones per internal channel (no hyphens: used in [expr])
JUST = "engjust"   # just-intonation offsets per pitch class


def build(out_dir):
    v = Canvas(w=1200, h=1050)
    v.comment("Host voice. Input from [poly]: 'key vel', key = channel * 128 + note.", 20, 5)
    v.comment("Internal channels: 17 * loop layer + MIDI channel (0 = Organelle keys). Master = 17 * layer + 1.", 20, 22)
    i_in = v.obj("inlet", 20, 50)
    unp = v.obj("unpack 0 0", 20, 75)
    v.c(i_in, 0, unp, 0)
    velf = v.obj("f", 20, 125)
    keyt = v.obj("t b f", 110, 100)
    v.c(unp, 1, velf, 1)
    v.c(unp, 0, keyt, 0)
    split = v.obj("expr int($f1 / 128); $f1 % 128", 160, 125)
    v.c(keyt, 1, split, 0)
    v.c(keyt, 0, velf, 0)
    sel0 = v.obj("sel 0", 20, 150)
    vm = v.obj("moses 0", 20, 137)            # velocity < 0 = legato: the voice moves to the new key, no new attack
    v.c(velf, 0, vm, 0)
    v.c(vm, 1, sel0, 0)

    # outputs to the engine (via sends that the dynamic slot listens to)
    s_pitch = v.obj("s $0-pitch", 20, 840)
    s_level = v.obj("s $0-level", 150, 840)
    s_timb = v.obj("s $0-timbre", 280, 840)

    # --- note on
    on_t = v.obj("t b f b", 80, 180)
    v.c(sel0, 1, on_t, 0)
    act1 = v.msg("1", 160, 210)
    v.c(on_t, 2, act1, 0)
    stopm = v.msg("stop", 200, 210)
    v.c(on_t, 2, stopm, 0)
    tbr = v.msg("0.5 0", 250, 210)
    v.c(on_t, 2, tbr, 0)
    v.c(tbr, 0, s_timb, 0)
    velc = v.obj("expr pow($f1 / 127, $f2)", 80, 240)
    v.c(on_t, 1, velc, 0)
    v.c(v.obj("r eng-curve", 220, 240), 0, velc, 1)
    # every level change goes through the shaper below as "level ms" (ms < 0: go there in -ms, no Release limit)
    s_lvq = v.obj("s $0-lvq", 80, 295)
    lvon = v.msg("$1 -4", 80, 270)
    v.c(velc, 0, lvon, 0)
    v.c(lvon, 0, s_lvq, 0)
    PITCH = (f"expr $f2 + $f3 + {BEND}[$f1] + ($f1 != 17 * int($f1 / 17) + 1) * {BEND}[17 * int($f1 / 17) + 1]"
             f" + {JUST}[($f2 - $f4 + 120) % 12]")
    chA = v.obj("f", 20, 270)
    v.c(on_t, 0, chA, 0)
    pA = v.obj(PITCH, 20, 300)
    v.c(chA, 0, pA, 0)
    # glide (portamento). Every note start is kept in a 16-entry buffer (pitch, time, still held).
    # A new note looks back at the notes started more than 30 ms ago (not its own chord) and glides from
    # the nearest one (polyphonic: a chord slides into the next chord) or from the latest one ("From last").
    # "Glide legato" only uses notes that are still held. No source or Glide 0: "P 0" (time 0 = a new note).
    pt3 = v.obj("t f f f", 20, 315)
    v.c(pA, 0, pt3, 0)
    clk = v.obj("timer", 700, 300)                           # logical time since load (all voices agree)
    v.c(v.obj("loadbang", 700, 275), 0, clk, 0)
    srt = v.obj("t b b b f", 300, 300)
    v.c(pt3, 2, srt, 0)
    v.c(srt, 3, v.obj("v engsP", 400, 325), 0)
    v.c(srt, 2, clk, 1)
    v.c(clk, 0, v.obj("v engnow", 700, 325), 0)
    for i, (nm, val) in enumerate((("engsbd", 1e9), ("engsbp", -1), ("engslt", -1), ("engslp", -1))):
        mm = v.msg(str(val), 480 + i * 60, 325)
        v.c(srt, 1, mm, 0)
        v.c(mm, 0, v.obj(f"v {nm}", 480 + i * 60, 350), 0)
    lpn = v.obj("until", 300, 350)
    m16 = v.msg("16", 300, 325)
    v.c(srt, 0, m16, 0)
    v.c(m16, 0, lpn, 0)
    cnt = v.obj("f", 300, 375)
    v.c(lpn, 0, cnt, 0)
    inc = v.obj("+ 1", 340, 375)
    v.c(cnt, 0, inc, 0)
    v.c(inc, 0, cnt, 1)
    m0 = v.msg("0", 360, 325)
    v.c(srt, 1, m0, 0)
    v.c(m0, 0, cnt, 1)
    OK = ("((engpbuft[$f1] > 0) && (engnow - engpbuft[$f1] > 30) && (engnow - engpbuft[$f1] < 20000) && "
          "((enggwhen == 0) || (engpbufh[$f1] > 0)))")
    D = "(abs(engpbuf[$f1] - engsP) + (engnow - engpbuft[$f1]) / 1000)"     # + 1 semitone per second: recent chord first
    sx = v.obj(f"expr if({OK} && ({D} < engsbd), {D}, engsbd); if({OK} && ({D} < engsbd), engpbuf[$f1], engsbp); "
               f"if({OK} && (engpbuft[$f1] > engslt), engpbuft[$f1], engslt); "
               f"if({OK} && (engpbuft[$f1] > engslt), engpbuf[$f1], engslp)", 300, 400)
    v.c(cnt, 0, sx, 0)
    for i, nm in enumerate(("engsbd", "engsbp", "engslt", "engslp")):
        v.c(sx, i, v.obj(f"v {nm}", 300 + i * 70, 425), 0)
    gx = v.obj("expr if(enggfrom, engslp, engsbp) >= 0 && (engglide > 0); if(enggfrom, engslp, engsbp); $f1", 20, 365)
    v.c(pt3, 1, gx, 0)
    gpk = v.obj("pack 0 0 0", 20, 390)
    v.c(gx, 2, gpk, 2)
    v.c(gx, 1, gpk, 1)
    v.c(gx, 0, gpk, 0)
    gsel = v.obj("route 0 1", 20, 415)
    v.c(gpk, 0, gsel, 0)
    nog = v.msg("$2 0", 20, 440)
    v.c(gsel, 0, nog, 0)
    v.c(nog, 0, s_pitch, 0)
    gmsg = v.obj("expr $f1; $f2; engglide", 120, 440)
    v.c(gsel, 1, gmsg, 0)
    gp2 = v.obj("pack 0 0 0", 120, 465)
    for k in (2, 1, 0):
        v.c(gmsg, k, gp2, k)
    gm = v.msg("$1 0, $2 $3", 120, 490)
    v.c(gp2, 0, gm, 0)
    v.c(gm, 0, s_pitch, 0)
    gtim = v.obj("timer", 300, 515)
    gleft = v.obj("expr max(5, $f2 - $f1)", 300, 540)
    v.c(gtim, 0, gleft, 0)
    glen = v.obj("expr $f1 * engglide", 200, 515)            # glide length, for bends during the glide
    v.c(glen, 0, gleft, 1)
    v.c(gx, 0, glen, 0)
    # store this note in the buffer, remember its slot (cleared at note-off), restart the glide clock
    pst = v.obj("t f b b", 20, 540)
    v.c(pt3, 0, pst, 0)
    v.c(pst, 2, gtim, 0)
    myidx = v.obj("f -1", 100, 615)
    slot = v.obj("expr engpidx; (engpidx + 1) % 16", 100, 565)
    v.c(pst, 1, slot, 0)
    v.c(slot, 1, v.obj("v engpidx", 220, 590), 0)
    v.c(slot, 0, myidx, 1)
    myidx2 = v.obj("f -1", 220, 640)
    v.c(slot, 0, myidx2, 1)
    wt = v.obj("t f f f", 100, 590)
    v.c(slot, 0, wt, 0)
    for i, (tb, src) in enumerate((("engpbufh", "1"), ("engpbuft", "engnow"))):
        tw = v.obj(f"tabwrite {tb}", 300 + i * 120, 640)
        v.c(wt, 1 + i, tw, 1)
        ex = v.obj(f"expr {src}", 300 + i * 120, 615)
        v.c(wt, 1 + i, ex, 0)
        v.c(ex, 0, tw, 0)
    twp = v.obj("tabwrite engpbuf", 20, 640)
    v.c(wt, 0, twp, 1)
    v.c(pst, 0, twp, 0)
    v.c(pst, 0, v.obj("v englastp", 20, 615), 0)
    # --- note off
    off_t = v.obj("t b b", 20, 380)
    v.c(sel0, 0, off_t, 0)
    hof = v.obj("t b f", 160, 690)
    v.c(off_t, 1, myidx, 0)
    v.c(myidx, 0, hof, 0)
    hw = v.obj("tabwrite engpbufh", 160, 740)
    v.c(hof, 1, hw, 1)
    hz = v.msg("0", 160, 715)
    v.c(hof, 0, hz, 0)
    v.c(hz, 0, hw, 0)
    act0 = v.msg("0", 120, 410)
    v.c(off_t, 1, act0, 0)
    # note-off: fade to 0 at the Release rate, then switch the voice off once the fade is done
    offt2 = v.obj("t b b", 20, 410)
    v.c(off_t, 0, offt2, 0)
    lvoff = v.msg("0 10", 60, 440)
    v.c(offt2, 1, lvoff, 0)
    v.c(lvoff, 0, s_lvq, 0)
    lastms = v.obj("f", 20, 470)
    v.c(offt2, 0, lastms, 0)
    pad = v.obj("+ 50", 110, 470)
    v.c(lastms, 0, pad, 0)
    dly = v.obj("delay 200", 110, 500)
    v.c(pad, 0, dly, 0)
    v.c(stopm, 0, dly, 0)
    swoff = v.msg("0", 110, 530)
    v.c(dly, 0, swoff, 0)

    # active flag -> the engines in this voice ([r $0-act]: 1 while the note sounds or releases)
    actf = v.obj("f 0", 410, 780)
    v.c(act1, 0, actf, 0)
    v.c(swoff, 0, actf, 0)
    v.c(actf, 0, v.obj("s $0-act", 410, 805), 0)
    # --- bend updates
    rb = v.obj("r eng-bend", 450, 50)
    bf = v.obj("expr ($f1 == $f2) || ($f1 == 17 * int($f2 / 17) + 1)", 450, 75)
    v.c(rb, 0, bf, 0)
    bs = v.obj("sel 1", 450, 100)
    v.c(bf, 0, bs, 0)
    chB = v.obj("f", 450, 125)
    v.c(bs, 0, chB, 0)
    pB = v.obj(PITCH, 450, 150)
    v.c(chB, 0, pB, 0)
    pbt = v.obj("t f f f b", 450, 175)
    v.c(pB, 0, pbt, 0)
    v.c(pbt, 3, gtim, 1)                       # elapsed since the glide started -> time left
    bpk = v.obj("pack 0 0", 450, 225)
    v.c(gleft, 0, bpk, 1)
    v.c(pbt, 1, v.obj("v englastp", 560, 200), 0)
    # legato / bend: the buffer keeps this voice's current pitch
    bwt = v.obj("t f b", 650, 200)
    v.c(pbt, 2, bwt, 0)
    bwr = v.obj("tabwrite engpbuf", 650, 250)
    v.c(bwt, 0, bwr, 0)
    v.c(bwt, 1, myidx2, 0)
    bmo = v.obj("moses 0", 720, 225)
    v.c(bmo, 1, bwr, 1)
    v.c(myidx2, 0, bmo, 0)
    v.c(pbt, 0, bpk, 0)
    bm = v.msg("$1 $2", 450, 250)
    v.c(bpk, 0, bm, 0)
    v.c(bm, 0, s_pitch, 0)
    # legato (velocity < 0): the key has changed (channel/note already updated) - glide there without a new attack
    lgt = v.obj("t b b", 300, 150)
    v.c(vm, 0, lgt, 0)
    lg = v.obj("expr max(5, engglide)", 360, 175)
    v.c(lgt, 1, lg, 0)
    v.c(lg, 0, gleft, 1)
    v.c(lgt, 1, gtim, 0)
    v.c(lgt, 0, chB, 0)
    for r, inl in (("r eng-octave", 2), ("r eng-key", 3)):
        o = v.obj(r, 800 + inl * 100, 125)
        v.c(o, 0, pA, inl)
        v.c(o, 0, pB, inl)

    # --- breath "ch note value" (note -1 = whole channel)
    rbr = v.obj("r eng-breath", 450, 230)
    brx = v.obj("expr if(($f1 == $f4) && (($f2 < 0) || ($f2 == $f5)) && $f6, $f3, -1)", 450, 255)
    v.c(rbr, 0, brx, 0)
    brm = v.obj("moses 0", 450, 280)
    v.c(brx, 0, brm, 0)
    brmsg = v.msg("$1 15", 510, 305)
    v.c(brm, 1, brmsg, 0)
    v.c(brmsg, 0, s_lvq, 0)
    # --- level shaper. Release caps how fast the level may fall: a drop of d takes at least d * Release ms.
    # The DM48X fades breath to 0 before its note-off, so without this Release had nothing left to fade.
    # Now a breath that stops fades out over Release; a breath that falls slower is followed as is.
    # Rises keep their own time. Tracks where the engine's line~ is, so a new value starts from there.
    lu = v.obj("unpack 0 0", 20, 875)
    v.c(v.obj("r $0-lvq", 20, 850), 0, lu, 0)
    CUR = "if($f3 >= $f6, $f5, $f4 + ($f5 - $f4) * $f3 / max(1, $f6))"
    lx = v.obj(f"expr $f1; if($f2 < 0, -$f2, if($f1 >= {CUR}, $f2, max($f2, ({CUR} - $f1) * $f7))); {CUR}",
               20, 950)
    v.c(lu, 1, lx, 1)
    lt = v.obj("t f b", 20, 900)
    v.c(lu, 0, lt, 0)
    tmr = v.obj("timer", 120, 925)
    v.c(lt, 1, tmr, 1)
    v.c(tmr, 0, lx, 2)
    v.c(lt, 0, lx, 0)
    # expr sends its outputs right to left as it evaluates them: store, then write back once all are out
    stc, std = v.obj("f", 200, 1000), v.obj("f", 250, 1000)
    v.c(lx, 2, stc, 1)                     # start = where the line~ is now
    v.c(lx, 1, std, 1)                     # duration
    v.c(lx, 1, lastms, 1)
    lpk = v.obj("pack 0 0", 20, 1000)
    v.c(lx, 1, lpk, 1)
    lt2 = v.obj("t f f b", 20, 975)
    v.c(lx, 0, lt2, 0)
    v.c(lt2, 2, tmr, 0)                    # restart the clock
    v.c(lt2, 2, stc, 0)
    v.c(lt2, 2, std, 0)
    v.c(stc, 0, lx, 3)
    v.c(std, 0, lx, 5)
    v.c(lt2, 1, lx, 4)                     # target
    v.c(lt2, 0, lpk, 0)
    v.c(lpk, 0, s_level, 0)
    rel = v.obj("r eng-release", 300, 925)
    v.c(rel, 0, lx, 6)
    r200 = v.msg("200", 400, 925)
    v.c(v.obj("loadbang", 400, 900), 0, r200, 0)
    v.c(r200, 0, lx, 6)
    # --- timbre "ch value"
    rtb = v.obj("r eng-timbre", 450, 350)
    tbx = v.obj("expr if(($f1 == $f3) && $f4, $f2, -1)", 450, 375)
    v.c(rtb, 0, tbx, 0)
    tbm = v.obj("moses 0", 450, 400)
    v.c(tbx, 0, tbm, 0)
    tbmsg = v.msg("$1 20", 510, 425)
    v.c(tbm, 1, tbmsg, 0)
    v.c(tbmsg, 0, s_timb, 0)

    for dst, inl in ((chA, 1), (chB, 1), (bf, 1), (brx, 3), (tbx, 2)):
        v.c(split, 0, dst, inl)
    for dst, inl in ((pA, 1), (pB, 1), (brx, 4)):
        v.c(split, 1, dst, inl)
    for g in (act1, act0):
        v.c(g, 0, brx, 5)
        v.c(g, 0, tbx, 3)

    # --- every engine is created once, at start-up, inside [pd $0-eng] (one [ehost] per engine).
    # Only the selected one runs (switch~); switching fades 15 ms out, then 15 ms in - nothing is created while
    # you play, so Pd never has to rebuild its DSP graph mid-performance.
    rc = v.obj("r eng-clear", 700, 450)
    idf = v.obj("f $0", 700, 475)
    v.c(rc, 0, idf, 0)
    v.c(idf, 0, v.msg("; pd-$1-eng clear", 700, 500), 0)
    ra = v.obj("r eng-add", 900, 450)                       # "index engines/NAME"
    at = v.obj("t a b", 900, 475)
    v.c(ra, 0, at, 0)
    idf2 = v.obj("f $0", 1000, 500)
    v.c(at, 1, idf2, 0)
    lp = v.obj("list prepend", 900, 525)
    v.c(idf2, 0, lp, 1)
    v.c(at, 0, lp, 0)
    v.c(lp, 0, v.msg("; pd-$1-eng obj 10 10 ehost $1 $3 $2", 900, 550), 0)
    v.sub(Canvas("$0-eng", w=500, h=300), 700, 600)
    v.c(v.obj("catch~ $0-out", 20, 870), 0, v.obj("outlet~", 20, 895), 0)
    v.save(os.path.join(out_dir, "voice.pd"))


def build_ehost(out_dir):
    """ehost.pd: one engine inside a voice.  Args: voice-id, engines/NAME, index."""
    h = Canvas(w=900, h=520)
    h.comment("One engine in one voice. Runs (switch~) only while it is the selected engine (eng-esel) and the voice "
              "sounds. Selected: waits 15 ms (the old engine fades out), then fades in over 15 ms.", 20, 5)
    p, l, t = h.obj("r $1-pitch", 20, 40), h.obj("r $1-level", 120, 40), h.obj("r $1-timbre", 220, 40)
    eng = h.obj("$2 eng", 20, 90)
    for i, src in enumerate((p, l, t)):
        h.c(src, 0, eng, i)
    g = h.obj("*~", 20, 140)
    h.c(eng, 0, g, 0)
    gl = h.obj("line~", 120, 115)
    h.c(gl, 0, g, 1)
    h.c(g, 0, h.obj("throw~ $1-out", 20, 170), 0)
    # stored state, read in order by the recompute below: act (voice sounds), sel, fading
    a2, s2, f2 = h.obj("f 0", 400, 340), h.obj("f 0", 450, 340), h.obj("f 0", 500, 340)
    rec = h.obj("t b b b", 400, 315)
    ex = h.obj("expr $f1 && ($f2 || $f3)", 400, 390)
    h.c(rec, 2, f2, 0)
    h.c(rec, 1, s2, 0)
    h.c(rec, 0, a2, 0)
    h.c(f2, 0, ex, 2)
    h.c(s2, 0, ex, 1)
    h.c(a2, 0, ex, 0)
    h.c(ex, 0, h.obj("switch~", 400, 415), 0)
    # voice on/off
    at = h.obj("t b f", 400, 65)
    h.c(h.obj("r $1-act", 400, 40), 0, at, 0)
    h.c(at, 1, a2, 1)
    h.c(at, 0, rec, 0)
    # selection
    sx = h.obj("== $3", 550, 40)
    h.c(h.obj("r eng-esel", 550, 15), 0, sx, 0)
    sc = h.obj("change -1", 550, 65)
    h.c(sx, 0, sc, 0)
    st = h.obj("t b f f", 550, 90)
    h.c(sc, 0, st, 0)
    h.c(st, 2, s2, 1)
    ss = h.obj("sel 1 0", 550, 115)
    h.c(st, 1, ss, 0)
    h.c(st, 0, rec, 0)
    # selected: no fading flag, fade in after 15 ms
    sel_t = h.obj("t b b b", 550, 140)
    h.c(ss, 0, sel_t, 0)
    dout = h.obj("delay 20", 750, 190)
    stp = h.msg("stop", 650, 165)
    h.c(sel_t, 2, stp, 0)
    h.c(stp, 0, dout, 0)
    z = h.msg("0", 600, 165)
    h.c(sel_t, 1, z, 0)
    h.c(z, 0, f2, 1)
    din = h.obj("delay 15", 550, 190)
    h.c(sel_t, 0, din, 0)
    fin = h.msg("1 15", 550, 215)
    h.c(din, 0, fin, 0)
    h.c(fin, 0, gl, 0)
    # deselected: fade out over 15 ms, keep running 20 ms (fading), then stop
    des_t = h.obj("t b b", 750, 140)
    h.c(ss, 1, des_t, 0)
    one = h.msg("1", 800, 165)
    h.c(des_t, 1, one, 0)
    h.c(one, 0, f2, 1)
    fout = h.msg("0 15", 850, 165)
    h.c(des_t, 0, fout, 0)
    h.c(fout, 0, gl, 0)
    h.c(des_t, 0, dout, 0)
    endf = h.obj("t b b", 750, 215)
    h.c(dout, 0, endf, 0)
    zz = h.msg("0", 800, 240)
    h.c(endf, 1, zz, 0)
    h.c(zz, 0, f2, 1)
    h.c(endf, 0, rec, 0)
    h.save(os.path.join(out_dir, "ehost.pd"))
